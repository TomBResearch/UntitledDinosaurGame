/**
 * The ingest path (P03-b, P03-c stage L precondition, P03-f overflow).
 *
 * "Handlers on the transport side validate and enqueue; they never move a player, never consume an
 * observation and never touch a watermark." Everything decided here is about *admission into a
 * queue*: classification and the association gate. Validation that needs the entity's watermark, its
 * epoch or the tick's batch registry happens in stage S, inside the frozen set; capacity is applied
 * by the core, which owns the queues.
 *
 * Refusing a message for an association that has no issued epoch uses `EPOCH_MISMATCH` because the
 * closed rejection vocabulary (protocol.md 4.3) has no "unassociated" code, and the honest statement
 * about such a message is that the epoch it declares is not one this region has issued for that
 * entity. `RATE_LIMITED` is the volume code, used for every capacity refusal.
 */

import type { EntityId, RejectionCode, SessionEpoch } from '@udg/protocol';

import type { ArrivalRecord, Disposition, LifecycleStatus } from './types.js';

export type AdmissionQueue = 'continuous' | 'discrete' | 'control';

export type AdmissionDecision =
  | { readonly ok: true; readonly arrival: ArrivalRecord; readonly queue: AdmissionQueue }
  | {
      readonly ok: false;
      readonly arrival: ArrivalRecord;
      readonly code: RejectionCode;
      readonly disposition: Disposition;
      readonly reason: string;
    };

export interface IngestContext {
  /** `null` when the entity has never joined, or has departed and been released. */
  lifecycleFor(entityId: EntityId): LifecycleStatus | null;
  epochFor(entityId: EntityId): SessionEpoch | null;
}

/** Decide which queue an arrival belongs to, or refuse it. Mutates nothing. */
export const admit = (arrival: ArrivalRecord, context: IngestContext): AdmissionDecision => {
  // Lifecycle events travel the same queue as messages so that stage L can apply them inside the
  // frozen set (P03-b). They are generated by the server, never by a client.
  if (arrival.control !== null) {
    return { ok: true, arrival, queue: 'control' };
  }

  const lifecycle = context.lifecycleFor(arrival.entityId);
  if (lifecycle === null) {
    return {
      ok: false,
      arrival,
      code: 'EPOCH_MISMATCH',
      disposition: 'refused:epoch',
      reason: 'the association has no issued epoch: the entity has neither joined nor been retained',
    };
  }
  if (lifecycle !== 'active') {
    return {
      ok: false,
      arrival,
      code: 'EPOCH_MISMATCH',
      disposition: 'refused:epoch',
      reason: `the association is ${lifecycle}: no movement source is accepted after leave or expiry`,
    };
  }
  if (context.epochFor(arrival.entityId) === null) {
    return {
      ok: false,
      arrival,
      code: 'EPOCH_MISMATCH',
      disposition: 'refused:epoch',
      reason: 'the association reports no epoch',
    };
  }

  switch (arrival.kind) {
    case 'unknownMessage':
      return {
        ok: false,
        arrival,
        code: 'INVALID_PAYLOAD',
        disposition: 'refused:structural',
        reason: 'the payload does not declare one of the three accepted message shapes',
      };
    case 'direct':
      return { ok: true, arrival, queue: 'continuous' };
    case 'moveTo':
    case 'cancelPath':
      return { ok: true, arrival, queue: 'discrete' };
  }
};

/** Why a capacity refusal happened, recorded so AC-3e can report overflow by cause. */
export type OverflowCause =
  | 'continuous-capacity'
  | 'discrete-capacity-entity'
  | 'discrete-capacity-room'
  | 'control-capacity'
  | 'ordinal-exhausted';
