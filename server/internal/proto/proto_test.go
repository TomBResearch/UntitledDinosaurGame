func encodeAll(t testing.TB, msgs []Message) []byte {
	t.Helper()
	var b []byte
	for _, m := range msgs {
		var err error
		if b, err = Append(b, m); err != nil {
			t.Fatalf("encode %v: %v", m.MessageID(), err)
		}
	}
	return b
}

func dirOf(m Message) Direction {
	d, _, _ := m.MessageID().info()
	return d
}

func TestRoundTrip(t *testing.T) {
	for _, s := range samples() {
		frame := encodeAll(t, s.msgs)
		got, err := Decode(frame, dirOf(s.msgs[0]))
		if err != nil {
			t.Fatalf("%s: decode: %v", s.name, err)
		}
		if !reflect.DeepEqual(got, s.msgs) {
			t.Errorf("%s: round trip changed the messages:\n got %#v\nwant %#v", s.name, got, s.msgs)
		}
	}
}

func TestGolden(t *testing.T) {
	var out strings.Builder
	out.WriteString("# Cross-language test vectors: name, then the encoded frame in hex.\n")
	out.WriteString("# Generated by `go test ./internal/proto -update` (from server/). The Go and GDScript\n")
	out.WriteString("# tests both check their encoders against this file. Don't edit it by hand.\n")
	for _, s := range samples() {
		fmt.Fprintf(&out, "%s %x\n", s.name, encodeAll(t, s.msgs))
	}
	if *update {
		if err := os.WriteFile(goldenPath, []byte(out.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("%v (run: go test ./internal/proto -update)", err)
	}
	if string(want) != out.String() {
		t.Errorf("encoding no longer matches %s. If the wire format change is intended, run "+
			"go test ./internal/proto -update and update the GDScript samples to match.\n got:\n%s",
			goldenPath, out.String())
	}
}

func goldenFrames(t testing.TB) [][]byte {
	t.Helper()
	f, err := os.Open(goldenPath)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	var frames [][]byte
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if line == "" || line[0] == '#' {
			continue
		}
		_, hx, _ := strings.Cut(line, " ")
		b, err := hex.DecodeString(hx)
		if err != nil {
			t.Fatal(err)
		}
		frames = append(frames, b)
	}
	return frames
}

// frame builds one message by hand: id, then the varint length of body, then body.
func frame(id MsgID, body ...byte) []byte {
	e := encoder{b: []byte{byte(id)}}
	e.uvarint(uint64(len(body)))
	return append(e.b, body...)
}

func TestHelloVersionCheck(t *testing.T) {
	good := &Hello{ProtocolHash: ProtocolHash, Ticket: "t", ContentHash: "c", ClientVersion: "v"}
	b := encodeAll(t, []Message{good})
	if h, err := CheckHello(b); err != nil || !reflect.DeepEqual(h, good) {
		t.Fatalf("CheckHello(good) = %v, %v", h, err)
	}

	stale := *good
	stale.ProtocolHash = ProtocolHash + 1
	if _, err := CheckHello(encodeAll(t, []Message{&stale})); !errors.Is(err, ErrProtocolMismatch) {
		t.Errorf("wrong protocol hash: got %v, want ErrProtocolMismatch", err)
	}

	// An old client whose hello no longer decodes still gets a clean version mismatch,
	// because only the id and the first field are read before the hash is compared.
	e := encoder{}
	e.u32(ProtocolHash ^ 0xffff)
	oldLayout := frame(MsgHello, append(e.b, 0xff, 0xff, 0xff)...)
	if _, err := CheckHello(oldLayout); !errors.Is(err, ErrProtocolMismatch) {
		t.Errorf("old hello layout: got %v, want ErrProtocolMismatch", err)
	}

	right := encoder{}
	right.u32(ProtocolHash)
	for name, b := range map[string][]byte{
		"empty":                nil,
		"ping first":           encodeAll(t, []Message{&Ping{}}),
		"two messages":         append(bytes.Clone(b), b...),
		"right hash, bad body": frame(MsgHello, append(right.b, 0xff, 0xff, 0xff)...),
		"no hash bytes":        {byte(MsgHello)},
	} {
		if _, err := CheckHello(b); err == nil {
			t.Errorf("%s: CheckHello accepted it", name)
		}
	}
}

func TestDecodeRejectsMalformedInput(t *testing.T) {
	long := bytes.Repeat([]byte{'x'}, 1025)
	helloLongTicket := append([]byte{1, 0x81, 0x08}, long...) // hash 1, then a 1025-byte ticket
	helloLongTicket = append(helloLongTicket, 0, 0)
	cases := []struct {
		name string
		dir  Direction
		in   []byte
		want error
	}{
		{"unknown id 0", FromClient, []byte{0, 0}, ErrUnknownMessage},
		{"unknown id 200", FromServer, []byte{200, 0}, ErrUnknownMessage},
		{"server message from a client", FromClient, encodeAll(t, []Message{&Welcome{}}), ErrWrongDirection},
		{"client message from the server", FromServer, encodeAll(t, []Message{&MoveTo{}}), ErrWrongDirection},
		{"id only", FromClient, []byte{byte(MsgPing)}, ErrTruncated},
		{"length past the end", FromClient, frame(MsgPing, 1)[:2], ErrTruncated},
		{"declared length over the message's limit", FromClient, frame(MsgChatSay, make([]byte, 483)...), ErrTooLarge},
		{"huge declared length", FromClient, []byte{byte(MsgPing), 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f}, ErrTooLarge},
		{"string over its limit", FromClient, frame(MsgHello, helloLongTicket...), ErrInvalid},
		{"trailing bytes", FromClient, frame(MsgMoveTo, 0, 0, 0, 0), ErrInvalid},
		{"non-minimal varint", FromServer, frame(MsgEntityLeave, 0x80, 0x00), ErrInvalid},
		{"varint too long", FromClient, frame(MsgHello, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x01), ErrInvalid},
		{"u32 overflow", FromServer, frame(MsgEntityLeave, 0x80, 0x80, 0x80, 0x80, 0x10), ErrInvalid},
		{"unused flag bit", FromServer, frame(MsgEntityEnter, 0x08, 1, 0, 0, 0, 0, 0, 0, 0), ErrInvalid},
		{"enum out of range", FromServer, frame(MsgEntityEnter, 0, 1, 5, 0, 0, 0, 0, 0, 0), ErrInvalid},
		{"invalid UTF-8", FromClient, frame(MsgChatSay, 2, 0xc3, 0x28), ErrInvalid},
		{"list over its limit", FromServer, frame(MsgPathStarted, append([]byte{1, 0, 0, 65}, make([]byte, 65*3)...)...), ErrInvalid},
		{"list longer than the bytes left", FromServer, frame(MsgPathStarted, 1, 0, 0, 10, 0, 0, 0), ErrTruncated},
		{"good message then garbage", FromServer, append(encodeAll(t, []Message{&EntityLeave{Entity: 1}}), 0xee), ErrUnknownMessage},
	}
	for _, c := range cases {
		msgs, err := Decode(c.in, c.dir)
		if !errors.Is(err, c.want) {
			t.Errorf("%s: got %v, want %v", c.name, err, c.want)
		}
		if msgs != nil {
			t.Errorf("%s: returned messages along with the error", c.name)
		}
	}
}

func TestEveryTruncationIsRejected(t *testing.T) {
	for _, s := range samples() {
		if len(s.msgs) != 1 {
			continue // a multi-message frame cut at a message boundary is valid
		}
		b := encodeAll(t, s.msgs)
		for n := 1; n < len(b); n++ {
			if _, err := Decode(b[:n], dirOf(s.msgs[0])); !errors.Is(err, ErrTruncated) {
				t.Errorf("%s cut to %d of %d bytes: got %v, want ErrTruncated", s.name, n, len(b), err)
			}
		}
	}
}

func TestEncodeRejectsOutOfRange(t *testing.T) {
	cases := map[string]Message{
		"string over its limit": &ChatSay{Text: strings.Repeat("a", 481)},
		"invalid UTF-8":         &ChatSay{Text: "\xff"},
		"u64 over 2^63-1":       &Ping{ClientTime: 1 << 63},
		"enum out of range":     &Chat{Role: 5},
		"list over its limit":   &PathStarted{Path: Path{Waypoints: make([]Pos, 65)}},
		"nested optional":       &EntityEnter{Path: &Path{Waypoints: make([]Pos, 65)}},
	}
	for name, m := range cases {
		prefix := []byte{9, 9}
		b, err := Append(prefix, m)
		if !errors.Is(err, ErrOutOfRange) {
			t.Errorf("%s: got %v, want ErrOutOfRange", name, err)
		}
		if !bytes.Equal(b, prefix) {
			t.Errorf("%s: Append changed the buffer on error", name)
		}
	}
}

// The computed size limits must be exact: a maximal message hits them and still decodes.
func TestMaximalMessagesFitTheLimits(t *testing.T) {
	maxPos := Pos{-1 << 31, -1 << 31, -1 << 31}
	full := make([]Pos, 64)
	for i := range full {
		full[i] = maxPos
	}
	maxPath := Path{StartTick: 1<<32 - 1, Speed: 1<<32 - 1, Waypoints: full}
	hello := &Hello{ProtocolHash: 1<<32 - 1, Ticket: strings.Repeat("t", 1024),
		ContentHash: strings.Repeat("c", 64), ClientVersion: strings.Repeat("v", 32)}
	enter := &EntityEnter{Entity: 1<<32 - 1, Kind: EntityKindNPC, TypeID: strings.Repeat("t", 32),
		Name: strings.Repeat("n", 64), Position: maxPos, Path: &maxPath, HP: 255, InCombat: true,
		Look: &Look{BodyType: strings.Repeat("b", 32), SkinTone: strings.Repeat("s", 32), HairStyle: strings.Repeat("h", 32),
			HairColour: strings.Repeat("c", 32), Beard: strings.Repeat("d", 32)}}
	for _, c := range []struct {
		m    Message
		want int
	}{{hello, MaxClientMessageSize}, {enter, MaxServerMessageSize}} {
		b := encodeAll(t, []Message{c.m})
		if len(b) != c.want {
			t.Errorf("maximal %v is %d bytes, limit says %d", c.m.MessageID(), len(b), c.want)
		}
		if _, err := Decode(b, dirOf(c.m)); err != nil {
			t.Errorf("maximal %v doesn't decode: %v", c.m.MessageID(), err)
		}
	}
}

// checkDecode is the decoder's contract: never panic, and anything accepted re-encodes to
// exactly the same bytes (the encoding is canonical).
func checkDecode(t testing.TB, data []byte) {
	for _, dir := range []Direction{FromClient, FromServer} {
		msgs, err := Decode(data, dir)
		if err != nil {
			continue
		}
		var re []byte
		for _, m := range msgs {
			if re, err = Append(re, m); err != nil {
				t.Fatalf("decoded %x but can't re-encode %v: %v", data, m.MessageID(), err)
			}
		}
		if !bytes.Equal(re, data) {
			t.Fatalf("decoded %x but it re-encodes as %x", data, re)
		}
	}
	_, _ = CheckHello(data)
}

// A quick, deterministic fuzz pass for the fast check. FuzzDecode explores further in the slow lane.
func TestRandomMutations(t *testing.T) {
	seeds := goldenFrames(t)
	rng := rand.New(rand.NewPCG(1, 2))
	for range 30000 {
		b := bytes.Clone(seeds[rng.IntN(len(seeds))])
		for range 1 + rng.IntN(3) {
			switch i := rng.IntN(len(b) + 1); rng.IntN(4) {
			case 0:
				if i < len(b) {
					b[i] = byte(rng.Uint32())
				}
			case 1:
				b = append(b[:i], append([]byte{byte(rng.Uint32())}, b[i:]...)...)
			case 2:
				if i < len(b) {
					b = append(b[:i], b[i+1:]...)
				}
			case 3:
				b = b[:i]
			}
		}
		checkDecode(t, b)
	}
}

func FuzzDecode(f *testing.F) {
	for _, b := range goldenFrames(f) {
		f.Add(b)
	}
	f.Fuzz(func(t *testing.T, data []byte) { checkDecode(t, data) })
}
