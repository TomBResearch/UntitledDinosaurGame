package main

import (
	"fmt"
	"strings"
)

// GenGDScript returns the GDScript codec for the schema: one script, class_name Proto, with an
// inner class per struct and message. It passes the client's strict typing warnings.
func GenGDScript(s *Schema) []byte {
	g := &gdGen{}
	g.p("# Code generated by protogen from protocol/messages.schema. DO NOT EDIT.")
	g.p("# Regenerate with tools/protogen.sh.")
	g.p("class_name Proto")
	g.p("extends RefCounted")
	g.p("## The binary network protocol between the client and a world server. The wire format is")
	g.p("## described in protocol/README.md. Build a message (Proto.MoveTo.new()), send")
	g.p("## Proto.encode(msg), and pass each received frame to Proto.decode(frame, Proto.Dir.FROM_SERVER).")
	g.p("")
	g.p("## Identifies this version of the schema. Sent as the first field of hello.")
	g.p("const PROTOCOL_HASH: int = 0x%08x", s.Hash)
	g.p("")
	g.p("## Who sends a message.")
	g.p("enum Dir { FROM_CLIENT = 1, FROM_SERVER = 2 }")
	g.p("")
	for _, e := range s.Enums {
		g.doc(e.Doc, "")
		g.p("enum %s {", e.Name)
		for _, v := range e.Values {
			g.doc(v.Doc, "\t")
			g.p("\t%s = %d,", strings.ToUpper(v.Name), v.Value)
		}
		g.p("}")
		g.p("")
	}
	g.p("# Message ids.")
	for _, m := range s.Messages {
		g.p("const MSG_%s: int = %d", strings.ToUpper(m.Name), m.ID)
	}
	g.p("")
	g.b.WriteString(gdRuntime)
	g.p("")
	g.p("")
	g.p("## A new, empty message for an id, or null if the id is unknown.")
	g.p("static func new_message(id: int) -> Message:")
	g.p("\tmatch id:")
	for _, m := range s.Messages {
		g.p("\t\tMSG_%s:", strings.ToUpper(m.Name))
		g.p("\t\t\treturn %s.new()", camel(m.Name))
	}
	g.p("\treturn null")
	for _, st := range s.Structs {
		g.classDecl(st, st.Name)
	}
	for _, m := range s.Messages {
		g.classDecl(m, camel(m.Name))
	}
	return []byte(g.b.String())
}

type gdGen struct{ b strings.Builder }

func (g *gdGen) p(format string, args ...any) {
	fmt.Fprintf(&g.b, format, args...)
	g.b.WriteByte('\n')
}

func (g *gdGen) doc(lines []string, indent string) {
	for _, l := range lines {
		g.p("%s## %s", indent, l)
	}
}

func gdType(t *Type) string {
	switch t.Kind {
	case KBool:
		return "bool"
	case KU8, KU16, KU32, KU64, KI32:
		return "int"
	case KPos:
		return "Vector3i"
	case KString:
		return "String"
	case KList:
		return "Array[" + gdType(t.Elem) + "]"
	case KEnum, KStruct:
		return t.Name
	}
	panic("unknown kind")
}

func gdDefault(t *Type) string {
	switch t.Kind {
	case KBool:
		return "false"
	case KU8, KU16, KU32, KU64, KI32:
		return "0"
	case KPos:
		return "Vector3i.ZERO"
	case KString:
		return `""`
	case KList:
		return "[]"
	case KEnum:
		return t.Name + "." + strings.ToUpper(t.Enum.Values[0].Name)
	case KStruct:
		if t.Optional {
			return "null"
		}
		return t.Name + ".new()"
	}
	panic("unknown kind")
}

func (g *gdGen) classDecl(st *Struct, name string) {
	g.p("")
	g.p("")
	g.doc(st.Doc, "")
	base := "RefCounted"
	if st.IsMessage {
		base = "Message"
	}
	g.p("class %s extends %s:", name, base)
	for _, f := range st.Fields {
		g.doc(f.Doc, "\t")
		g.p("\tvar %s: %s = %s", f.Name, gdType(f.Type), gdDefault(f.Type))
	}
	if st.IsMessage {
		dir := "FROM_SERVER"
		if st.FromClient {
			dir = "FROM_CLIENT"
		}
		if len(st.Fields) > 0 {
			g.p("")
		}
		g.p("\tfunc message_id() -> int:")
		g.p("\t\treturn MSG_%s", strings.ToUpper(st.Name))
		g.p("")
		g.p("\tfunc message_name() -> String:")
		g.p("\t\treturn %q", st.Name)
		g.p("")
		g.p("\tfunc direction() -> Dir:")
		g.p("\t\treturn Dir.%s", dir)
		g.p("")
		g.p("\tfunc max_body_size() -> int:")
		g.p("\t\treturn %d", st.MaxSize())
	}
	g.p("")
	w, r := "w", "r"
	if len(st.Fields) == 0 {
		w, r = "_w", "_r"
	}
	g.p("\tfunc encode_body(%s: Writer) -> void:", w)
	if len(st.Fields) == 0 {
		g.p("\t\tpass")
	}
	if st.FlagBits > 0 {
		g.p("\t\tvar f: int = 0")
		for _, f := range st.Fields {
			if !f.Type.UsesFlag() {
				continue
			}
			if f.Type.Kind == KBool {
				g.p("\t\tif %s:", f.Name)
			} else {
				g.p("\t\tif %s != null:", f.Name)
			}
			g.p("\t\t\tf |= 1 << %d", f.Flag)
		}
		g.p("\t\tw.flags(f, %d)", st.FlagBytes())
	}
	for _, f := range st.Fields {
		g.encodeField(f)
	}
	g.p("")
	g.p("\tfunc decode_body(%s: Reader) -> void:", r)
	if len(st.Fields) == 0 {
		g.p("\t\tpass")
	}
	if st.FlagBits > 0 {
		g.p("\t\tvar f: int = r.flags(%d, %d)", st.FlagBytes(), st.FlagBits)
	}
	for _, f := range st.Fields {
		g.decodeField(f)
	}
}

func (g *gdGen) encodeField(f *Field) {
	switch f.Type.Kind {
	case KBool:
		// In the flag bytes.
	case KList:
		g.p("\t\tif w.list_len(%s.size(), %d):", f.Name, f.Type.Max)
		g.p("\t\t\tfor item in %s:", f.Name)
		if f.Type.Elem.Kind == KStruct {
			g.p("\t\t\t\tif item == null:")
			g.p("\t\t\t\t\tw.fail(\"%s has a null element\")", f.Name)
			g.p("\t\t\t\telse:")
			g.p("\t\t\t\t\titem.encode_body(w)")
		} else {
			g.p("\t\t\t\t%s", gdEncodeValue(f.Type.Elem, "item"))
		}
	case KStruct:
		if f.Type.Optional {
			g.p("\t\tif %s != null:", f.Name)
			g.p("\t\t\t%s.encode_body(w)", f.Name)
		} else {
			g.p("\t\tif %s == null:", f.Name)
			g.p("\t\t\tw.fail(\"%s is null\")", f.Name)
			g.p("\t\telse:")
			g.p("\t\t\t%s.encode_body(w)", f.Name)
		}
	default:
		g.p("\t\t%s", gdEncodeValue(f.Type, f.Name))
	}
}

func gdEncodeValue(t *Type, v string) string {
	switch t.Kind {
	case KU8:
		return fmt.Sprintf("w.u8(%s)", v)
	case KU16:
		return fmt.Sprintf("w.u16(%s)", v)
	case KU32:
		return fmt.Sprintf("w.u32(%s)", v)
	case KU64:
		return fmt.Sprintf("w.u64(%s)", v)
	case KI32:
		return fmt.Sprintf("w.i32(%s)", v)
	case KPos:
		return fmt.Sprintf("w.vec3(%s)", v)
	case KString:
		return fmt.Sprintf("w.utf8(%s, %d)", v, t.Max)
	case KEnum:
		return fmt.Sprintf("w.enum8(%s, %d)", v, len(t.Enum.Values))
	}
	panic("unsupported value kind")
}

func (g *gdGen) decodeField(f *Field) {
	switch f.Type.Kind {
	case KBool:
		g.p("\t\t%s = (f & (1 << %d)) != 0", f.Name, f.Flag)
	case KList:
		g.p("\t\tfor _i in range(r.list_len(%d)):", f.Type.Max)
		if f.Type.Elem.Kind == KStruct {
			g.p("\t\t\tvar item := %s.new()", f.Type.Elem.Name)
			g.p("\t\t\titem.decode_body(r)")
			g.p("\t\t\t%s.append(item)", f.Name)
		} else {
			g.p("\t\t\t%s.append(%s)", f.Name, gdDecodeValue(f.Type.Elem))
		}
	case KStruct:
		if f.Type.Optional {
			g.p("\t\tif (f & (1 << %d)) != 0:", f.Flag)
			g.p("\t\t\t%s = %s.new()", f.Name, f.Type.Name)
			g.p("\t\t\t%s.decode_body(r)", f.Name)
		} else {
			g.p("\t\t%s = %s.new()", f.Name, f.Type.Name)
			g.p("\t\t%s.decode_body(r)", f.Name)
		}
	default:
		g.p("\t\t%s = %s", f.Name, gdDecodeValue(f.Type))
	}
}

func gdDecodeValue(t *Type) string {
	switch t.Kind {
	case KU8:
		return "r.u8()"
	case KU16:
		return "r.u16()"
	case KU32:
		return "r.u32()"
	case KU64:
		return "r.u64()"
	case KI32:
		return "r.i32()"
	case KPos:
		return "r.vec3()"
	case KString:
		return fmt.Sprintf("r.utf8(%d)", t.Max)
	case KEnum:
		return fmt.Sprintf("r.enum8(%d) as %s", len(t.Enum.Values), t.Name)
	}
	panic("unsupported value kind")
}

// gdRuntime is the hand-written part of the GDScript codec, copied into the generated file.
const gdRuntime = `const _MAX_U63: int = 0x7fffffffffffffff


## Appends m to w.buf (id byte, varint body length, body). Returns false and sets w.error if a
## field is out of range; w.buf is then unchanged.
static func encode_into(w: Writer, m: Message) -> bool:
	var body := Writer.new()
	m.encode_body(body)
	if body.error != "":
		w.fail("%s: %s" % [m.message_name(), body.error])
		return false
	w.buf.append(m.message_id())
	w.uvarint(body.buf.size())
	w.buf.append_array(body.buf)
	return true


## Encodes one message as a frame. Returns an empty array if a field is out of range.
static func encode(m: Message) -> PackedByteArray:
	var w := Writer.new()
	if not encode_into(w, m):
		return PackedByteArray()
	return w.buf


## Decodes a frame of messages sent in direction. Any malformed message, or one meant for the
## other direction, fails the whole frame: the result then has an error and no messages.
static func decode(frame: PackedByteArray, direction: Dir) -> Decoded:
	var out := Decoded.new()
	var r := Reader.new(frame, 0, frame.size())
	while r.pos < r.end:
		var id := r.u8()
		var m := new_message(id)
		if m == null:
			return out.failed("unknown message id %d" % id)
		if m.direction() != direction:
			return out.failed("%s sent in the wrong direction" % m.message_name())
		var n := r.uvarint(_MAX_U63)
		if r.error != "":
			return out.failed("%s: %s" % [m.message_name(), r.error])
		if n > m.max_body_size():
			return out.failed("%s: message too large (%d bytes)" % [m.message_name(), n])
		if n > r.end - r.pos:
			return out.failed("%s: truncated" % m.message_name())
		var body := Reader.new(frame, r.pos, r.pos + n)
		m.decode_body(body)
		if body.error == "" and body.pos != body.end:
			body.fail("%d trailing bytes" % (body.end - body.pos))
		if body.error != "":
			return out.failed("%s: %s" % [m.message_name(), body.error])
		out.messages.append(m)
		r.pos += n
	return out


## One protocol message. Each message in the schema is a subclass.
class Message extends RefCounted:
	func message_id() -> int:
		return 0

	func message_name() -> String:
		return ""

	func direction() -> Dir:
		return Dir.FROM_CLIENT

	func max_body_size() -> int:
		return 0

	func encode_body(_w: Writer) -> void:
		pass

	func decode_body(_r: Reader) -> void:
		pass


## The result of decode: the messages in a frame, or an error and no messages.
class Decoded extends RefCounted:
	var messages: Array[Message] = []
	var error: String = ""

	func failed(msg: String) -> Decoded:
		messages.clear()
		error = msg
		return self


## Encodes values onto buf. After the first error it keeps the error; the caller drops buf.
class Writer extends RefCounted:
	var buf: PackedByteArray = PackedByteArray()
	var error: String = ""

	func fail(msg: String) -> void:
		if error == "":
			error = msg

	func uvarint(v: int) -> void:
		var x := v
		while x >= 0x80:
			buf.append((x & 0x7f) | 0x80)
			x >>= 7
		buf.append(x)

	func u8(v: int) -> void:
		if v < 0 or v > 0xff:
			fail("u8 out of range: %d" % v)
			return
		buf.append(v)

	func u16(v: int) -> void:
		if v < 0 or v > 0xffff:
			fail("u16 out of range: %d" % v)
			return
		buf.append(v & 0xff)
		buf.append(v >> 8)

	func u32(v: int) -> void:
		if v < 0 or v > 0xffffffff:
			fail("u32 out of range: %d" % v)
			return
		uvarint(v)

	func u64(v: int) -> void:
		if v < 0:
			fail("u64 out of range: %d" % v)
			return
		uvarint(v)

	func i32(v: int) -> void:
		if v < -0x80000000 or v > 0x7fffffff:
			fail("i32 out of range: %d" % v)
			return
		uvarint((v << 1) ^ (v >> 63))

	func vec3(v: Vector3i) -> void:
		i32(v.x)
		i32(v.y)
		i32(v.z)

	func utf8(s: String, max_bytes: int) -> void:
		var b := s.to_utf8_buffer()
		if b.size() > max_bytes:
			fail("string of %d bytes, limit %d" % [b.size(), max_bytes])
			return
		uvarint(b.size())
		buf.append_array(b)

	func list_len(n: int, max_len: int) -> bool:
		if n > max_len:
			fail("list of %d, limit %d" % [n, max_len])
			return false
		uvarint(n)
		return true

	func enum8(v: int, count: int) -> void:
		if v < 0 or v >= count:
			fail("enum value out of range: %d" % v)
			return
		buf.append(v)

	func flags(f: int, nbytes: int) -> void:
		for i in range(nbytes):
			buf.append((f >> (8 * i)) & 0xff)


## Reads values from buf[pos..end). After the first error every read returns zero and the
## error is kept, so generated code needn't check after each field.
class Reader extends RefCounted:
	var buf: PackedByteArray
	var pos: int
	var end: int
	var error: String = ""

	func _init(b: PackedByteArray, start: int, stop: int) -> void:
		buf = b
		pos = start
		end = stop

	func fail(msg: String) -> void:
		if error == "":
			error = msg
		pos = end

	## A minimally encoded varint of at most 63 bits, no larger than limit.
	func uvarint(limit: int) -> int:
		var v: int = 0
		var shift: int = 0
		while true:
			if shift > 56:
				fail("varint too long")
				return 0
			if pos >= end:
				fail("truncated")
				return 0
			var c: int = buf[pos]
			pos += 1
			v |= (c & 0x7f) << shift
			if c < 0x80:
				if c == 0 and shift > 0:
					fail("non-minimal varint")
					return 0
				break
			shift += 7
		if v > limit:
			fail("varint %d over %d" % [v, limit])
			return 0
		return v

	func u8() -> int:
		if pos >= end:
			fail("truncated")
			return 0
		pos += 1
		return buf[pos - 1]

	func u16() -> int:
		if pos + 2 > end:
			fail("truncated")
			return 0
		pos += 2
		return buf[pos - 2] | (buf[pos - 1] << 8)

	func u32() -> int:
		return uvarint(0xffffffff)

	func u64() -> int:
		return uvarint(_MAX_U63)

	func i32() -> int:
		var z := uvarint(0xffffffff)
		return (z >> 1) ^ -(z & 1)

	func vec3() -> Vector3i:
		var x := i32()
		var y := i32()
		var z := i32()
		return Vector3i(x, y, z)

	func utf8(max_bytes: int) -> String:
		var n := uvarint(max_bytes)
		if n > end - pos:
			fail("truncated")
			return ""
		var s := buf.slice(pos, pos + n).get_string_from_utf8()
		pos += n
		return s

	## A list length. Every element takes at least a byte, so a length longer than the bytes
	## left is rejected straight away.
	func list_len(max_len: int) -> int:
		var n := uvarint(max_len)
		if n > end - pos:
			fail("truncated")
			return 0
		return n

	func enum8(count: int) -> int:
		var v := u8()
		if v >= count:
			fail("enum value out of range: %d" % v)
			return 0
		return v

	## nbytes of flag bits, of which the low nbits are used; the rest must be zero.
	func flags(nbytes: int, nbits: int) -> int:
		if pos + nbytes > end:
			fail("truncated")
			return 0
		var f: int = 0
		for i in range(nbytes):
			f |= buf[pos + i] << (8 * i)
		pos += nbytes
		if nbits < 64 and (f >> nbits) != 0:
			fail("unused flag bits set")
			return 0
		return f`
